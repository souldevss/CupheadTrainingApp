function updateReferenceTimes() {
  for (const category of categories)
    for (const route of category.subOptions || [category]) {
      const records = WR_REFERENCES[route.id];
      for (const level of route.islands.flatMap((island) => island.levels)) {
        const record = records?.[level.name];
        record && ([level.wrTime, level.wrPlayer, level.wrUrl] = record), level.times = generateRankTimes(level.fRankTime, { wrTime: level.wrTime });
      }
    }
  refreshDeveloperRankOverrides(), calculateRankMultipliers();
}
function calculateCategoryMultipliers(categoryData) {
  let wrToFratios = [];
  if ((categoryData.levels || categoryData.islands?.flatMap((island) => island.levels) || []).forEach((level) => {
    if (level.fRankTime && level.times && level.times.length >= 19) {
      const wrTime = Number.isFinite(level.wrTime) ? level.wrTime : level.times[0], fRankTime = level.fRankTime;
      wrTime > 0 && fRankTime > 0 && wrToFratios.push(wrTime / fRankTime);
    }
  }), wrToFratios.length === 0) return null;
  const avgRatio = wrToFratios.reduce((sum, ratio) => sum + ratio, 0) / wrToFratios.length;
  return createRankMultipliers(avgRatio);
}
function calculateRankMultipliers() {
  for (const category of categories)
    for (const route of category.subOptions || [category]) {
      const multipliers = calculateCategoryMultipliers(route);
      multipliers && (route.rankMultipliers = multipliers, regenerateCategoryTimes(route, multipliers));
    }
}
function regenerateCategoryTimes(categoryData, multipliers) {
  (categoryData.levels || categoryData.islands?.flatMap((island) => island.levels) || []).forEach((level) => {
    level.fRankTime && (level.times = generateRankTimes(level.fRankTime, {
      wrTime: level.wrTime,
      fallbackMultipliers: multipliers
    }));
  });
}
